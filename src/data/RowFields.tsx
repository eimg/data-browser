import { useEffect, useRef, useState } from 'react';
import type { Column, LargeFields, Row } from './types';
import { fullCell, largeField, type ReadCell } from './row-values';

type Field = { mode: 'default' | 'null' | 'value' | 'unchanged'; value: string };

const canUseDefault = (column: Column) => /auto_increment/i.test(column.extra) || column.defaultValue !== null;
const insertMode = (column: Column): Field['mode'] => canUseDefault(column) ? 'default' : column.nullable ? 'null' : 'value';
// Match the visible initial fields even when Save is clicked without editing them.
export function initialInsertValues(columns: Column[]): Row {
  return Object.fromEntries(columns.filter(c => !c.generated && !c.binary && !canUseDefault(c)).map(c => [c.name, c.nullable ? null : '']));
}

function startingField(column: Column, original?: Row): Field {
  if (!original) return { mode: insertMode(column), value: '' };
  return original[column.name] === null ? { mode: 'null', value: '' } : { mode: 'value', value: original[column.name] ?? '' };
}

export default function RowFields({ columns, original, largeFields = {}, readCell, onLoadingChange, onChange }: { columns: Column[]; original?: Row; largeFields?: LargeFields; readCell?: ReadCell; onLoadingChange?: (loading: boolean) => void; onChange: (row: Row) => void }) {
  const [fields, setFields] = useState(() => Object.fromEntries(columns.map(c => [c.name, original && largeField(largeFields, c.name) ? { mode: 'unchanged' as const, value: '' } : startingField(c, original)])));
  const currentFields = useRef(fields);
  const originals = useRef({ ...original });
  const loading = useRef<AbortController | null>(null);
  const [loadingName, setLoadingName] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => () => { loading.current?.abort(); }, []);
  function change(name: string, field: Field) {
    const next = { ...currentFields.current, [name]: field }; currentFields.current = next; setFields(next);
    const values: Row = Object.create(null);
    for (const c of columns) if (!c.generated && !c.binary && !['default', 'unchanged'].includes(next[c.name].mode)) {
      const value = next[c.name].mode === 'null' ? null : next[c.name].value;
      if (!original || value !== originals.current[c.name]) values[c.name] = value;
    }
    onChange(values);
  }
  async function load(column: string) {
    if (!readCell || loading.current) return;
    const controller = new AbortController(); loading.current = controller;
    setLoadingName(column); setError(null); onLoadingChange?.(true);
    try {
      const value = await fullCell(readCell, column, controller.signal);
      originals.current[column] = value;
      change(column, { mode: 'value', value });
    } catch (error) { if (!controller.signal.aborted) setError(String(error instanceof Error ? error.message : error)); }
    finally { if (!controller.signal.aborted) { loading.current = null; setLoadingName(null); onLoadingChange?.(false); } }
  }
  // Blank nullable text is NULL. Choosing Value while blank keeps an empty string.
  function choose(column: Column, mode: Field['mode']) {
    const current = fields[column.name];
    change(column.name, mode === 'value' ? { mode, value: current.mode === 'value' ? current.value : '' } : { mode, value: '' });
  }
  return <div className="db-row-fields">{error && <p className="notice error" role="alert">{error}</p>}{loadingName && <p role="status">Loading {loadingName}…</p>}{columns.map(c => {
    const field = fields[c.name];
    const large = largeField(largeFields, c.name);
    return <div key={c.name} className="db-row-field"><label htmlFor={`row-${c.name}`}>{c.name}<small>{c.type}{c.columnKey === 'PRI' ? ' · primary key' : ''}{c.generated || c.binary ? ' · read-only' : ''}</small></label>
      {c.generated || c.binary ? <div><code>{original?.[c.name] ?? (c.binary ? 'Binary value · use SQL' : 'Generated by the database')}{large && '…'}</code>{large && <p className="db-hint">Preview · {large.length.toLocaleString()} characters. Open the row viewer to read the complete value.</p>}</div> : <>
        <select disabled={!!loadingName} aria-label={`${c.name} value mode`} value={field.mode} onChange={e => choose(c, e.target.value as Field['mode'])}>{original && largeField(largeFields, c.name) && <option value="unchanged">Keep current value</option>}{!original && canUseDefault(c) && <option value="default">{/auto_increment/i.test(c.extra) ? 'Auto' : 'Use default'}</option>}<option value="value">{large ? 'Replace value' : 'Value'}</option>{c.nullable && <option value="null">NULL</option>}</select>
        {large && field.mode === 'unchanged' ? <div><p className="db-hint">Preview · {large.length.toLocaleString()} characters. The full value will be kept.</p><pre className="db-large-preview">{original?.[c.name]}…</pre>{readCell && <button type="button" className="secondary" disabled={!!loadingName} onClick={() => void load(c.name)}>Load {c.name} to edit</button>}</div> : <textarea id={`row-${c.name}`} aria-label={`${c.name} value`} rows={2} wrap={large || field.value.length > 16384 ? 'off' : 'soft'} disabled={field.mode === 'default' || !!loadingName} value={field.value} onChange={e => change(c.name, { mode: c.nullable && e.target.value === '' ? 'null' : 'value', value: e.target.value })} placeholder={field.mode === 'null' ? 'Leave blank for NULL' : field.mode === 'value' ? 'Empty text is an empty string' : 'Let the database supply this value'} />}
      </>}
    </div>;
  })}</div>;
}
